import { test, expect } from '@playwright/test';

test('Marswalk plan checks oxygen, cooling, science and return reserve before launch', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await page.getByRole('button', { name: 'Marswalk', exact: true }).click();
  const plan = page.getByLabel('Marswalk life support planner');
  await expect(plan).toContainText('Choose a start and destination');
  await page.getByRole('button', { name: 'Try a route' }).click();
  await expect(plan.getByLabel('Oxygen budget including reserve')).toBeVisible();
  await plan.getByText('Suit & science plan', { exact: true }).click();
  await plan.getByLabel('Cooling capacity (W)').fill('700');
  await plan.getByLabel('Mission duration (min)').fill('480');
  await expect(page.getByRole('button', { name: 'Walk route', exact: true })).toBeEnabled();
  await plan.getByLabel('Usable oxygen (L, STPD)').fill('50');
  await expect(plan).toContainText('Not enough oxygen for the return and reserve.');
  await expect(page.getByRole('button', { name: 'Walk route', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Drive route', exact: true })).toBeEnabled();
  await plan.getByLabel('Usable oxygen (L, STPD)').fill('600');
  await page.getByRole('button', { name: 'Walk route', exact: true }).click();
  const suit = page.getByLabel('Marswalk suit model');
  await expect(suit).toBeVisible();
  await suit.getByRole('button', { name: /SUIT MODEL/ }).click();
  await expect(suit).toContainText('Gait estimate');
  await suit.getByRole('button', { name: 'Practice a solar-storm alert' }).click();
  await expect(suit).toContainText('Practice alert · return to shelter');
  await expect(suit).toContainText('no live radiation or storm feed');
  await suit.getByRole('button', { name: 'Practice a solar-storm alert' }).click();
  await suit.getByRole('button', { name: /SUIT MODEL/ }).click();
  await page.getByRole('button', { name: 'Resume simulation', exact: true }).click();
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getEVA().elapsed), { timeout: 15000 }).toBeGreaterThan(.3);
  await page.keyboard.down('KeyW');
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTelemetry().speed), { timeout: 15000 }).toBeGreaterThan(.6);
  expect(await page.evaluate(() => window.__MARS_SIM__.getTelemetry().speed)).toBeLessThan(1.5);
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getEVA().watts), { timeout: 15000 }).toBeGreaterThan(200);
  await page.keyboard.up('KeyW');
  await page.evaluate(() => document.exitPointerLock());
  await expect.poll(() => page.evaluate(() => document.pointerLockElement === null)).toBe(true);
  const clock = await page.evaluate(() => window.__MARS_SIM__.getEVA().elapsed);
  await page.waitForTimeout(600);
  expect(await page.evaluate(() => window.__MARS_SIM__.getEVA().elapsed)).toBeCloseTo(clock, 0);
  await suit.getByRole('button', { name: /SUIT MODEL/ }).click();
  await suit.getByRole('button', { name: 'Head home · retrace trail' }).click();
  await expect(suit).toContainText('Retracing your trail');
  await suit.getByRole('button', { name: 'End suit simulation' }).click();
  await expect(suit).toHaveCount(0);
  const live = page.getByRole('region', { name: 'Live telemetry' });
  await expect(live.locator('dt')).toHaveCount(4);
  expect(errors).toEqual([]);
});

test('science work at a nearby destination charges the suit budget once', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await page.getByRole('button', { name: 'Marswalk', exact: true }).click();
  await page.getByRole('button', { name: 'Octavia E. Butler Landing Site', exact: true }).click();
  await page.getByText('Layers', { exact: true }).click();
  await page.getByRole('button', { name: 'Science sites', exact: true }).click();
  await page.getByText('Layers', { exact: true }).click();
  const map = page.getByRole('img', { name: 'Detailed traverse map' });
  const target = await map.evaluate(svg => {
    const t = window.__MARS_SIM__.getTerrain();
    const p = t.location(18.44462715, 77.45088572);
    const q = new DOMPoint(p.x + t.metadata.widthMeters / 2 + 24, p.z + t.metadata.depthMeters / 2).matrixTransform(svg.getScreenCTM());
    return { x: q.x, y: q.y };
  });
  await page.mouse.click(target.x, target.y);
  await page.getByRole('button', { name: 'Walk route', exact: true }).click();
  const suit = page.getByLabel('Marswalk suit model');
  await suit.getByRole('button', { name: /SUIT MODEL/ }).click();
  const work = suit.getByRole('button', { name: 'Log 20 min of science' });
  await expect(work).toBeEnabled();
  const oxygen = await page.evaluate(() => window.__MARS_SIM__.getEVA().oxygenLeft);
  await work.click();
  const model = await page.evaluate(() => window.__MARS_SIM__.getEVA());
  expect(model.elapsed).toBe(1200);
  expect(model.oxygenLeft).toBeLessThan(oxygen - 20);
  await expect(suit.getByRole('button', { name: 'Science work logged' })).toBeDisabled();
});
