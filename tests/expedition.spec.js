import { test, expect } from '@playwright/test';

test('opens real Jezero terrain and inspects its map layers', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await expect(page.getByRole('heading', { name: 'Jezero Expedition Planner' })).toBeVisible();
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTerrain().surfaceFlags?.length)).toBeGreaterThan(0);
  await page.getByText('Layers', { exact: true }).click();
  await page.getByRole('button', { name: 'Elevation', exact: true }).click();
  await page.getByText('Layers', { exact: true }).click();
  await page.getByRole('button', { name: 'Hazards', exact: true }).click();
  await expect(page.getByText(/Steep or locally uneven/)).toBeVisible();
  await page.getByRole('button', { name: 'Inspect', exact: true }).click();
  await page.getByRole('img', { name: 'Detailed traverse map' }).click();
  await expect(page.getByText('Terrain class')).toBeVisible();
  await page.getByRole('button', { name: 'Crater overview' }).click();
  await expect(page.getByRole('img', { name: 'Jezero crater elevation overview' })).toBeVisible();
  await page.getByRole('button', { name: 'Open detailed traverse area' }).press('Enter');
  await expect(page.getByRole('img', { name: 'Detailed traverse map' })).toBeVisible();
  await page.getByText('Layers', { exact: true }).click();
  await page.getByRole('button', { name: 'Geology', exact: true }).click();
  await page.getByText('Layers', { exact: true }).click();
  await page.getByText('Map information', { exact: true }).click();
  await expect(page.getByText('Published geologic units')).toBeVisible();
  await expect(page.getByText(/Eolian bedform unit/)).toBeVisible();
  await page.getByText('Perseverance weather observations').click();
  await page.getByRole('combobox', { name: 'Weather observation sol' }).selectOption('1130');
  await expect(page.getByText('777.1 Pa')).toBeVisible();
  await page.getByText('Layers', { exact: true }).click();
  await page.getByRole('button', { name: 'Thermal IR', exact: true }).click();
  await page.getByText('Layers', { exact: true }).click();
  await expect(page.getByText(/Mars Odyssey THEMIS nighttime infrared/)).toBeVisible();
  await page.getByRole('combobox', { name: 'Inspect science site' }).selectOption('seitah');
  await expect(page.getByText(/Investigate the olivine-rich/)).toBeVisible();
  await page.getByRole('combobox', { name: 'Inspect science site' }).selectOption('neretva');
  await expect(page.getByRole('img', { name: 'Jezero crater elevation overview' })).toBeVisible();
  await page.getByRole('button', { name: 'Return to surface' }).click();
  await expect(page.getByText('Jezero Crater / Western Delta')).toBeVisible();
  await page.getByRole('button', { name: 'Southeast hills' }).click();
  await expect(page.getByText('Hill southeast of Jezero Crater')).toBeVisible();
  expect(errors).toEqual([]);
});

test('calculates and follows a science route on the Jezero terrain', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await page.getByRole('button', { name: 'Try a route' }).click();
  await expect(page.getByRole('heading', { name: 'Two ways to explore' })).toBeVisible();
  await expect(page.getByRole('button', { name: /Easier terrain/ })).toContainText('2.60 km');
  await page.getByRole('button', { name: /Science stop/ }).click();
  await expect(page.getByText(/Via Western Delta front/)).toBeVisible();
  await page.getByText(/^Route details ·/).click();
  await expect(page.getByText('Estimated walk')).toBeVisible();
  await expect(page.getByText(/^Western Delta front ·/)).toBeVisible();
  await page.getByRole('button', { name: 'Walk route' }).click();
  await expect(page.getByLabel('Traverse guidance')).toContainText('Next stop 2');
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTelemetry().longitude)).toBeCloseTo(77.4509, 3);
  await page.getByRole('button', { name: 'Expedition map' }).click();
  await expect(page.getByRole('heading', { name: 'Two ways to explore' })).toBeVisible();
  await page.getByRole('button', { name: 'Mark avoid zone' }).click();
  await page.getByRole('img', { name: 'Detailed traverse map' }).click();
  await expect(page.getByRole('button', { name: 'Undo last avoid zone' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Mark avoid zone' })).toHaveAttribute('aria-pressed', 'true');
  expect(errors).toEqual([]);
});

test('starts driving at the chosen start pin with the cursor free', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await page.getByRole('button', { name: 'Set start', exact: true }).click();
  await page.getByRole('button', { name: 'Octavia E. Butler Landing Site', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Set destination', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Three Forks area', exact: true }).click();
  await page.getByRole('button', { name: 'Drive route', exact: true }).click();

  await expect(page.getByLabel('Traverse guidance')).toContainText('Next stop 2');
  await expect(page.locator('.sim-hud')).toHaveClass(/is-driving/);
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTelemetry().longitude)).toBeCloseTo(77.4509, 3);
  expect(await page.evaluate(() => document.pointerLockElement)).toBeNull();
  const hazards = page.getByRole('complementary', { name: 'Driving hazard map' });
  const hazardToggle = page.getByRole('button', { name: 'Hazards', exact: true });
  await expect(hazards).toBeVisible();
  await hazardToggle.click();
  await expect(hazards).toHaveCount(0);
  await hazardToggle.click();
  await expect(hazards).toBeVisible();
  const viewport = hazards.locator('svg');
  const initialView = await viewport.getAttribute('viewBox');
  await page.keyboard.down('KeyW');
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTelemetry().speed)).toBeGreaterThan(2);
  await page.keyboard.up('KeyW');
  await expect(viewport).not.toHaveAttribute('viewBox', initialView);
  await page.getByRole('button', { name: 'Expedition map' }).click();
  await expect(page.getByRole('button', { name: 'Drive route', exact: true })).toBeVisible();
});
