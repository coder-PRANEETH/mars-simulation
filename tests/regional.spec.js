import { test, expect } from '@playwright/test'

test('regional map exposes full field geology, imagery levels, persistent pins and correct regional drive start', async ({ page }) => {
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Explore Jezero' }).click()
  const extent = page.getByRole('combobox', { name: 'Map extent', exact: true })
  await expect(extent).toHaveValue('regional')
  await expect(extent).toBeEnabled()
  await expect(page.locator('.mission-coverage-note')).toContainText('40 m terrain grid')
  await page.getByRole('tab', { name: 'Discover', exact: true }).click()
  await page.getByRole('combobox', { name: 'Discover topic' }).selectOption('regions')
  const regions = page.getByLabel('Geologic region explorer')
  await expect(regions.getByRole('button')).toHaveCount(15)
  await regions.getByRole('combobox').selectOption('12')
  await expect(regions.getByLabel('Selected geologic region')).toContainText('2020 hypothesis')
  await expect(regions).toContainText('Pre-landing')
  await page.getByRole('button', { name: 'Collapse workspace', exact: true }).click()
  const map = page.getByRole('img', { name: 'Detailed traverse map' })
  await expect(map.locator('image').first()).toHaveAttribute('href', /overview.jpg/)
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click({ clickCount: 4 })
  await expect(map.getByLabel('HiRISE imagery inset over CTX regional terrain')).toBeVisible()
  await expect(map.locator('image[href$="jezero/texture.jpg"]')).toHaveCount(1)
  await page.getByRole('tab', { name: 'Route', exact: true }).click()
  await page.getByRole('button', { name: 'Try a route' }).click()
  await expect(page.getByRole('button', { name: 'Drive route', exact: true })).toBeEnabled({ timeout: 30000 })
  const pin = page.getByRole('button', { name: 'Set start', exact: true })
  await expect(pin).toContainText('Octavia')
  await extent.selectOption('local')
  await expect(pin).toContainText('Octavia')
  await expect(page.locator('.mission-coverage-note')).toContainText('8 m terrain grid')
  await extent.selectOption('regional')
  await page.getByRole('button', { name: 'Drive route', exact: true }).click()
  await expect(page.locator('.sim-hud')).toHaveClass(/is-driving/, { timeout: 30000 })
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTerrain().assetBase), { timeout: 30000 }).toMatch(/jezero-regional$/)
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTelemetry().longitude), { timeout: 15000 }).toBeCloseTo(77.4509, 3)
  expect(await page.evaluate(() => document.pointerLockElement)).toBeNull()
  expect(errors).toEqual([])
})
