import { test, expect } from '@playwright/test';

test('one workspace preserves route, suit settings, layers, zoom and selection across map inspection', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await page.getByRole('button', { name: 'Map layers', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Collected samples', exact: true }).check();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Set start', exact: true }).click();
  await page.getByRole('button', { name: 'Sample: Roubion', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Set destination', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByLabel('Place details', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Try a route' }).click();
  const launch = page.getByLabel('Route launch controls');
  await expect(launch.getByRole('button', { name: 'Drive route', exact: true })).toBeEnabled();
  const summary = await launch.locator('strong').innerText();
  const start = await page.getByRole('button', { name: 'Set start', exact: true }).locator('strong').innerText();
  await page.getByRole('button', { name: 'Map layers', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Hazards', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Geologic regions', exact: true }).check();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Map layers', exact: true })).toBeFocused();
  const map = page.getByRole('img', { name: 'Detailed traverse map' });
  await map.hover();
  await page.mouse.wheel(0, -250);
  const zoom = await map.getAttribute('viewBox');
  await page.getByRole('tab', { name: 'Marswalk', exact: true }).click();
  await expect(page.locator('[data-workspace]:visible')).toHaveCount(1);
  await expect(page.getByLabel('Marswalk life support planner')).toBeVisible();
  await expect(launch.locator('strong')).toHaveText(summary);
  await page.getByText('Suit & science plan', { exact: true }).click();
  await page.getByLabel('Usable oxygen (L, STPD)').fill('750');
  await page.getByRole('tab', { name: 'Discover', exact: true }).click();
  await page.getByRole('combobox', { name: 'Discover topic' }).selectOption('notes');
  await page.getByRole('button', { name: 'Dust & suits', exact: true }).click();
  await page.getByRole('tab', { name: 'Route', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Set start', exact: true }).locator('strong')).toHaveText(start);
  await expect(map).toHaveAttribute('viewBox', zoom);
  await page.getByRole('button', { name: 'Map layers', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Hazards', exact: true })).toBeChecked();
  await expect(page.getByRole('checkbox', { name: 'Geologic regions', exact: true })).toBeChecked();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Set start', exact: true }).click();
  await page.getByRole('tab', { name: 'Discover', exact: true }).click();
  await expect(page.getByText('Keep Mars dust outside.', { exact: true })).toBeVisible();
  await map.click();
  await expect(page.getByLabel('Place details', { exact: true })).toBeVisible();
  await expect(page.locator('[data-workspace]:visible')).toHaveCount(0);
  await expect(page.getByLabel('Location inspector', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to workspace', exact: true }).click();
  await expect(page.getByText('Keep Mars dust outside.', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Marswalk', exact: true }).click();
  await expect(page.getByLabel('Usable oxygen (L, STPD)')).toHaveValue('750');
  await page.getByRole('tab', { name: 'Route', exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Marswalk', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.keyboard.press('End');
  await expect(page.getByRole('tab', { name: 'Discover', exact: true })).toHaveAttribute('aria-selected', 'true');
});

test('phone workspace collapses while route launch and independent layer controls remain reachable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore Jezero' }).click();
  await page.getByRole('button', { name: 'Try a route' }).click();
  const drive = page.getByRole('button', { name: 'Drive route', exact: true });
  await expect(drive).toBeInViewport();
  const map = page.getByRole('img', { name: 'Detailed traverse map' });
  const height = (await map.boundingBox()).height;
  await page.getByRole('button', { name: 'Collapse workspace', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toBeHidden();
  expect((await map.boundingBox()).height).toBeGreaterThan(height + 100);
  await page.getByRole('button', { name: 'Map layers', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Geologic regions', exact: true }).check();
  await page.keyboard.press('Escape');
  await page.getByRole('tab', { name: 'Discover', exact: true }).click();
  await expect(page.getByRole('tabpanel')).toBeVisible();
  await expect(drive).toBeInViewport();
  const box = await drive.boundingBox();
  expect(await page.evaluate(({ x, y, width, height }) => document.elementFromPoint(x + width / 2, y + height / 2)?.closest('button')?.textContent.includes('Drive route'), box)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await drive.click();
  await expect(page.locator('.sim-hud')).toHaveClass(/is-driving/);
  await expect.poll(() => page.evaluate(() => window.__MARS_SIM__.getTelemetry().longitude)).toBeCloseTo(77.4509, 3);
});
